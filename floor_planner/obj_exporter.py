"""
OBJ/MTL file export for 3D floor plan visualization.

This module handles exporting floor plans to Wavefront OBJ format with MTL materials.
Supports multi-texture elements where different faces can have different textures.
"""

from pathlib import Path
from typing import TYPE_CHECKING
import math

from .material_properties import get_material_properties, format_mtl_color
from .texture_manager import TextureManager
from .elements.geometry_3d import is_3d_eligible

if TYPE_CHECKING:
    from .floor_plan import FloorPlan


class OBJExporter:
    """
    Exports floor plans to OBJ/MTL format.
    
    Handles:
        - Vertex, normal, and texture coordinate generation
        - Triangle face generation with correct winding
        - Material definitions with multi-texture support
        - Texture file copying to output directory
    """
    
    def __init__(self, floor_plan: 'FloorPlan', output_dir: Path, config_dir: Path):
        """
        Initialize OBJ exporter.
        
        Args:
            floor_plan: FloorPlan to export
            output_dir: Directory for output files (OBJ, MTL, textures)
            config_dir: Directory containing YAML config (for relative texture paths)
        """
        self.floor_plan = floor_plan
        self.output_dir = Path(output_dir)
        self.config_dir = Path(config_dir)
        
        # Create output directory
        self.output_dir.mkdir(parents=True, exist_ok=True)
        
        # Initialize texture manager
        # Use absolute paths based on floor_planner package location
        floor_planner_dir = Path(__file__).parent.parent  # Go up from floor_planner/obj_exporter.py to floor_planner/
        default_texture_dir = floor_planner_dir / 'textures' / 'defaults'
        fallback_texture_dir = floor_planner_dir / 'textures' / 'fallback'
        output_texture_dir = self.output_dir / 'textures'
        self.texture_manager = TextureManager(default_texture_dir, output_texture_dir, fallback_texture_dir)
        
        # Track vertices and materials globally across all elements
        self.global_vertices = []
        self.global_normals = []
        self.global_texcoords = []
        self.materials = {}  # material_name → {element_type, face, texture_path, properties}
        
    def export(self, obj_filename: str = None, mtl_filename: str = None):
        """
        Export floor plan to OBJ and MTL files.
        
        Args:
            obj_filename: Output OBJ filename (default: floor_plan_title.obj)
            mtl_filename: Output MTL filename (default: floor_plan_title.mtl)
        """
        # Generate filenames from floor plan title if not provided
        if obj_filename is None:
            safe_title = self._sanitize_filename(self.floor_plan.title or 'floor_plan')
            obj_filename = f"{safe_title}.obj"
            mtl_filename = f"{safe_title}.mtl"
        
        obj_path = self.output_dir / obj_filename
        mtl_path = self.output_dir / mtl_filename
        
        print(f"Exporting floor plan to 3D: {obj_path}")
        
        # Generate OBJ file
        with open(obj_path, 'w') as obj_file:
            self._write_obj_file(obj_file, mtl_filename)
        
        # Generate MTL file
        with open(mtl_path, 'w') as mtl_file:
            self._write_mtl_file(mtl_file)
        
        print(f"  OBJ file: {obj_path}")
        print(f"  MTL file: {mtl_path}")
        print(f"  Textures: {self.texture_manager.output_texture_dir}")
        print(f"  Materials: {len(self.materials)}")
    
    def _write_obj_file(self, obj_file, mtl_filename: str):
        """Write OBJ file content."""
        
        # Write header
        obj_file.write(f"# Floor Plan: {self.floor_plan.title}\n")
        obj_file.write("# Generated by floor_planner\n")
        obj_file.write(f"# Total elements: {len([e for e in self.floor_plan.elements if is_3d_eligible(e)])}\n")
        obj_file.write("\n")
        obj_file.write(f"mtllib {mtl_filename}\n")
        obj_file.write("\n")
        
        # Process each element
        vertex_offset = 0
        normal_offset = 0
        texcoord_offset = 0
        
        for element in self.floor_plan.elements:
            # Skip non-3D elements
            if not is_3d_eligible(element):
                continue
            
            # Check if element has 3D geometry generation
            if not hasattr(element, 'generate_vertices_and_indices'):
                print(f"Warning: Element {element.id} ({type(element).__name__}) "
                      f"does not support 3D geometry generation. Skipping.")
                continue
            
            # Generate geometry
            try:
                vertices, indices, face_groups = element.generate_vertices_and_indices()
            except Exception as e:
                print(f"Error generating geometry for {element.id}: {e}")
                continue
            
            # Write object header
            obj_file.write(f"# ============================================================================\n")
            obj_file.write(f"# Object: {element.id} ({type(element).__name__})\n")
            obj_file.write(f"# Position: {element.anchor_point}, Height: {element.v_anchor} to {element.v_anchor + element.height}\n")
            obj_file.write(f"# ============================================================================\n")
            obj_file.write("\n")
            obj_file.write(f"o {element.id}\n")
            obj_file.write("\n")
            
            # Write vertices
            for x, y, z in vertices:
                obj_file.write(f"v {x:.6f} {y:.6f} {z:.6f}\n")
                self.global_vertices.append((x, y, z))
            obj_file.write("\n")
            
            # Write texture coordinates (simple box mapping for now)
            texcoords = self._generate_box_texcoords(len(vertices))
            for u, v in texcoords:
                obj_file.write(f"vt {u:.6f} {v:.6f}\n")
                self.global_texcoords.append((u, v))
            obj_file.write("\n")
            
            # Write normals (calculate from triangle faces)
            normals = self._calculate_normals(vertices, indices)
            for nx, ny, nz in normals:
                obj_file.write(f"vn {nx:.6f} {ny:.6f} {nz:.6f}\n")
                self.global_normals.append((nx, ny, nz))
            obj_file.write("\n")
            
            # Resolve element textures
            element_type = type(element).__name__.lower()
            texture_spec = getattr(element, 'textures', None)
            texture_paths = self.texture_manager.resolve_element_textures(
                element_type, texture_spec, self.config_dir
            )
            
            # Write faces grouped by material
            self._write_element_faces(
                obj_file, element, indices, face_groups, texture_paths,
                vertex_offset, texcoord_offset, normal_offset
            )
            
            obj_file.write("\n")
            
            # Update offsets
            vertex_offset += len(vertices)
            texcoord_offset += len(texcoords)
            normal_offset += len(normals)
    
    def _write_element_faces(self, obj_file, element, indices, face_groups, 
                            texture_paths, vertex_offset, texcoord_offset, normal_offset):
        """
        Write faces for an element, grouped by material.
        
        Handles multi-texture elements by switching materials (usemtl) for different face groups.
        """
        element_type = type(element).__name__.lower()
        
        # Group triangles by texture
        # texture_to_triangles: {texture_path: [triangle_indices]}
        texture_to_triangles = {}
        
        for face_name, triangle_indices in face_groups.items():
            # Get texture for this face
            if face_name in texture_paths:
                texture_path = texture_paths[face_name]
            elif 'all' in texture_paths:
                texture_path = texture_paths['all']
            else:
                # Use first available texture
                texture_path = next(iter(texture_paths.values()))
            
            # Group triangles by texture
            if texture_path not in texture_to_triangles:
                texture_to_triangles[texture_path] = []
            texture_to_triangles[texture_path].extend(triangle_indices)
        
        # Write faces grouped by material
        for texture_path, triangle_indices in texture_to_triangles.items():
            # Generate unique material name
            material_name = self._get_or_create_material(
                element_type, texture_path
            )
            
            # Write material directive
            obj_file.write(f"usemtl {material_name}\n")
            
            # Write triangles
            for tri_idx in triangle_indices:
                v1, v2, v3 = indices[tri_idx]
                
                # OBJ uses 1-based indexing
                # Format: f v1/vt1/vn1 v2/vt2/vn2 v3/vt3/vn3
                v1_idx = vertex_offset + v1 + 1
                v2_idx = vertex_offset + v2 + 1
                v3_idx = vertex_offset + v3 + 1
                
                # Use same indices for texcoords and normals (simple mapping)
                vt1_idx = texcoord_offset + v1 + 1
                vt2_idx = texcoord_offset + v2 + 1
                vt3_idx = texcoord_offset + v3 + 1
                
                # Use per-face normal (same for all vertices in triangle)
                vn_idx = normal_offset + tri_idx + 1
                
                obj_file.write(f"f {v1_idx}/{vt1_idx}/{vn_idx} "
                             f"{v2_idx}/{vt2_idx}/{vn_idx} "
                             f"{v3_idx}/{vt3_idx}/{vn_idx}\n")
            
            obj_file.write("\n")
    
    def _get_or_create_material(self, element_type: str, texture_path: Path) -> str:
        """
        Get or create material name for element type and texture.
        
        Args:
            element_type: Type of element
            texture_path: Path to texture file
            
        Returns:
            Unique material name
        """
        # Generate material name from element type and texture filename
        texture_name = texture_path.stem  # filename without extension
        material_name = f"{element_type}_{texture_name}_material"
        
        # If material already exists, return it
        if material_name in self.materials:
            return material_name
        
        # Create new material entry
        self.materials[material_name] = {
            'element_type': element_type,
            'texture_path': texture_path,
            'properties': get_material_properties(element_type),
        }
        
        # Copy texture to output directory
        # Use just the filename (textures will be in output/textures/ directory)
        relative_path = texture_path.name
        self.texture_manager.copy_texture_to_output(texture_path, relative_path)
        
        return material_name
    
    def _write_mtl_file(self, mtl_file):
        """Write MTL file content."""
        
        mtl_file.write("# Material Library\n")
        mtl_file.write(f"# Floor Plan: {self.floor_plan.title}\n")
        mtl_file.write("# Generated by floor_planner\n")
        mtl_file.write("\n")
        
        for material_name, material_data in self.materials.items():
            props = material_data['properties']
            texture_path = material_data['texture_path']
            
            mtl_file.write(f"newmtl {material_name}\n")
            mtl_file.write(f"Ka {format_mtl_color(props['Ka'])}\n")
            mtl_file.write(f"Kd {format_mtl_color(props['Kd'])}\n")
            mtl_file.write(f"Ks {format_mtl_color(props['Ks'])}\n")
            mtl_file.write(f"Ns {props['Ns']:.1f}\n")
            
            # Texture reference (relative to MTL file location)
            texture_rel_path = self.texture_manager.get_relative_texture_path(texture_path)
            mtl_file.write(f"map_Kd {texture_rel_path}\n")
            mtl_file.write("\n")
    
    def _generate_box_texcoords(self, vertex_count: int) -> list[tuple[float, float]]:
        """
        Generate simple box-mapped texture coordinates.
        
        Args:
            vertex_count: Number of vertices
            
        Returns:
            List of (u, v) texture coordinates (0.0 to 1.0)
        """
        # Simple box mapping: 4 corners repeated for all faces
        base_coords = [
            (0.0, 0.0),  # bottom-left
            (1.0, 0.0),  # bottom-right
            (1.0, 1.0),  # top-right
            (0.0, 1.0),  # top-left
        ]
        
        # Repeat for all vertices
        coords = []
        for i in range(vertex_count):
            coords.append(base_coords[i % 4])
        
        return coords
    
    def _calculate_normals(self, vertices: list[tuple[float, float, float]], 
                          indices: list[tuple[int, int, int]]) -> list[tuple[float, float, float]]:
        """
        Calculate face normals for triangles.
        
        Args:
            vertices: List of vertex coordinates
            indices: List of triangle vertex indices
            
        Returns:
            List of normal vectors (one per triangle, not per vertex)
        """
        normals = []
        
        for v1_idx, v2_idx, v3_idx in indices:
            v1 = vertices[v1_idx]
            v2 = vertices[v2_idx]
            v3 = vertices[v3_idx]
            
            # Calculate edge vectors
            edge1 = (v2[0] - v1[0], v2[1] - v1[1], v2[2] - v1[2])
            edge2 = (v3[0] - v1[0], v3[1] - v1[1], v3[2] - v1[2])
            
            # Cross product for normal
            nx = edge1[1] * edge2[2] - edge1[2] * edge2[1]
            ny = edge1[2] * edge2[0] - edge1[0] * edge2[2]
            nz = edge1[0] * edge2[1] - edge1[1] * edge2[0]
            
            # Normalize
            length = math.sqrt(nx*nx + ny*ny + nz*nz)
            if length > 0.0001:
                nx /= length
                ny /= length
                nz /= length
            
            normals.append((nx, ny, nz))
        
        return normals
    
    def _sanitize_filename(self, filename: str) -> str:
        """
        Sanitize filename for filesystem compatibility.
        
        Args:
            filename: Original filename
            
        Returns:
            Sanitized filename
        """
        # Replace spaces and special chars with underscores
        safe = filename.replace(' ', '_')
        safe = ''.join(c for c in safe if c.isalnum() or c in ('_', '-'))
        return safe.lower()


def export_floor_plan_to_obj(floor_plan: 'FloorPlan', output_dir: Path, 
                             config_dir: Path):
    """
    Export floor plan to OBJ/MTL format.
    
    Args:
        floor_plan: FloorPlan to export
        output_dir: Directory for output files
        config_dir: Directory containing YAML config file
    """
    exporter = OBJExporter(floor_plan, output_dir, config_dir)
    exporter.export()


# Export public API
__all__ = [
    'OBJExporter',
    'export_floor_plan_to_obj',
]
