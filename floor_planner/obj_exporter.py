"""
OBJ/MTL file export for 3D floor plan visualization.

This module handles exporting floor plans to Wavefront OBJ format with MTL materials.
Supports multi-texture elements where different faces can have different textures.
"""

from pathlib import Path
from typing import TYPE_CHECKING
import math

from .material_manager import MaterialManager
from .texture_manager import TextureManager
from .geometry_3d import is_3d_eligible
from .elements.registry import get_element_type_from_instance
from .wall_openings import find_embedded_openings, generate_wall_with_openings
from .elements.foundation.basic import WallND
from .utils import WarnMsg

if TYPE_CHECKING:
    from .floor_plan import FloorPlan


class OBJExporter:
    """
    Exports floor plans to OBJ/MTL format.
    
    Handles:
        - Vertex, normal, and texture coordinate generation
        - Triangle face generation with correct winding
        - Material definitions with multi-texture support
        - Texture file copying to output directory
    """
    
    def __init__(self, floor_plan: 'FloorPlan', output_dir: Path, config_dir: Path):
        """
        Initialize OBJ exporter.
        
        Args:
            floor_plan: FloorPlan to export
            output_dir: Directory for output files (OBJ, MTL, textures)
            config_dir: Directory containing YAML config (for relative texture paths)
        """
        self.floor_plan = floor_plan
        self.output_dir = Path(output_dir)
        self.config_dir = Path(config_dir)
        
        # Create output directory
        self.output_dir.mkdir(parents=True, exist_ok=True)
        
        # Initialize texture manager
        # Use absolute paths based on floor_planner package location
        floor_planner_dir = Path(__file__).parent.parent  # Go up from floor_planner/obj_exporter.py to floor_planner/
        default_texture_dir = floor_planner_dir / 'textures' / 'defaults'
        fallback_texture_dir = floor_planner_dir / 'textures' / 'fallback'
        output_texture_dir = self.output_dir / 'textures'
        self.texture_manager = TextureManager(default_texture_dir, output_texture_dir, fallback_texture_dir)
        
        # Initialize material manager
        self.material_manager = MaterialManager(default_texture_dir, fallback_texture_dir)
        
        # Track vertices and materials globally across all elements
        self.global_vertices = []
        self.global_normals = []
        self.global_texcoords = []
        self.materials = {}  # material_name → {element_type, face, texture_path, properties}
        
    def export(self, obj_filename: str = None, mtl_filename: str = None):
        """
        Export floor plan to OBJ and MTL files.
        
        Args:
            obj_filename: Output OBJ filename (default: floor_plan_title.obj)
            mtl_filename: Output MTL filename (default: floor_plan_title.mtl)
        """
        # Generate filenames from floor plan title if not provided
        if obj_filename is None:
            safe_title = self._sanitize_filename(self.floor_plan.title or 'floor_plan')
            obj_filename = f"{safe_title}.obj"
            mtl_filename = f"{safe_title}.mtl"
        
        obj_path = self.output_dir / obj_filename
        mtl_path = self.output_dir / mtl_filename
        
        print(f"Exporting floor plan to 3D: {obj_path}")
        
        # Generate OBJ file
        with open(obj_path, 'w') as obj_file:
            self._write_obj_file(obj_file, mtl_filename)
        
        # Generate MTL file
        with open(mtl_path, 'w') as mtl_file:
            self._write_mtl_file(mtl_file)
        
        print(f"  OBJ file: {obj_path}")
        print(f"  MTL file: {mtl_path}")
        print(f"  Textures: {self.texture_manager.output_texture_dir}")
        print(f"  Materials: {len(self.materials)}")
    
    def _write_obj_file(self, obj_file, mtl_filename: str):
        """Write OBJ file content."""
        
        # Write header
        obj_file.write(f"# Floor Plan: {self.floor_plan.title}\n")
        obj_file.write("# Generated by floor_planner\n")
        obj_file.write(f"# Total elements: {len([e for e in self.floor_plan.elements if is_3d_eligible(e)])}\n")
        obj_file.write("\n")
        obj_file.write(f"mtllib {mtl_filename}\n")
        obj_file.write("\n")
        
        # Process each element
        vertex_offset = 0
        normal_offset = 0
        texcoord_offset = 0
        
        for element in self.floor_plan.elements:
            # Skip non-3D elements
            if not is_3d_eligible(element):
                continue
            
            # Check if element has 3D geometry generation
            if not hasattr(element, 'generate_vertices_and_indices'):
                WarnMsg(f"Element {element.get_id()} ({type(element).__name__}) does not support 3D geometry generation. Skipping.")
                continue
            
            # Generate geometry
            try:
                # Check if this is a wall that might have embedded doors/windows
                if isinstance(element, WallND):
                    # Find any doors/windows embedded in this wall
                    embedded_openings = find_embedded_openings(element, self.floor_plan.elements)
                    
                    if embedded_openings:
                        # Generate wall geometry with holes
                        vertices, indices, face_groups = generate_wall_with_openings(element, embedded_openings)
                    else:
                        # Standard wall geometry (no openings)
                        vertices, indices, face_groups = element.generate_vertices_and_indices()
                else:
                    # Standard geometry for non-wall elements
                    vertices, indices, face_groups = element.generate_vertices_and_indices()
            except Exception as e:
                print(f"Error generating geometry for {element.get_id()}: {e}")
                continue
            
            # Write object header
            obj_file.write(f"# ============================================================================\n")
            obj_file.write(f"# Object: {element.get_id()} ({type(element).__name__})\n")
            obj_file.write(f"# Position: {element.anchor_point}, Height: {element.v_anchor} to {element.v_anchor + element.height}\n")
            obj_file.write(f"# ============================================================================\n")
            obj_file.write("\n")
            obj_file.write(f"o {element.get_id()}\n")
            obj_file.write("\n")
            
            # Write vertices
            for x, y, z in vertices:
                obj_file.write(f"v {x:.6f} {y:.6f} {z:.6f}\n")
                self.global_vertices.append((x, y, z))
            obj_file.write("\n")
            
            # Write texture coordinates (box mapping with optional tiling)
            texcoords, vertex_to_uv_map = self._generate_element_texcoords(
                element, vertices, indices, face_groups
            )
            
            for u, v in texcoords:
                obj_file.write(f"vt {u:.6f} {v:.6f}\n")
                self.global_texcoords.append((u, v))
            obj_file.write("\n")
            
            # Write normals (calculate from triangle faces)
            normals = self._calculate_normals(vertices, indices)
            for nx, ny, nz in normals:
                obj_file.write(f"vn {nx:.6f} {ny:.6f} {nz:.6f}\n")
                self.global_normals.append((nx, ny, nz))
            obj_file.write("\n")
            
            # Resolve element textures
            element_type = get_element_type_from_instance(element)
        
            texture_paths = self.texture_manager.resolve_element_textures(
                element_type, self.config_dir
            )
            
            # Write faces grouped by material
            self._write_element_faces(
                obj_file, element, indices, face_groups, texture_paths,
                vertex_offset, texcoord_offset, normal_offset, vertex_to_uv_map
            )
            
            obj_file.write("\n")
            
            # Update offsets
            vertex_offset += len(vertices)
            texcoord_offset += len(texcoords)
            normal_offset += len(normals)
    
    def _write_element_faces(self, obj_file, element, indices, face_groups, 
                            texture_paths, vertex_offset, texcoord_offset, normal_offset, vertex_to_uv_map=None):
        """
        Write faces for an element, grouped by material.
        
        Handles multi-texture elements by switching materials (usemtl) for different face groups.
        
        Args:
            vertex_to_uv_map: Optional dict mapping (triangle_idx, vertex_pos) to UV index
        """
        element_type = get_element_type_from_instance(element)
        
        # Group triangles by texture
        # texture_to_triangles: {texture_path: set of triangle_indices}
        texture_to_triangles = {}
        
        for face_name, triangle_indices in face_groups.items():
            # Skip aggregate groups to avoid duplicates
            # 'all' and 'sides' are convenience groups that contain triangles already in other groups
            if face_name in ('all', 'sides'):
                continue
            
            # Get texture for this face
            if face_name in texture_paths:
                texture_path = texture_paths[face_name]
            elif 'all' in texture_paths:
                texture_path = texture_paths['all']
            else:
                # Use first available texture
                texture_path = next(iter(texture_paths.values()))
            
            # Group triangles by texture (use set to avoid duplicates)
            if texture_path not in texture_to_triangles:
                texture_to_triangles[texture_path] = set()
            texture_to_triangles[texture_path].update(triangle_indices)
        
        # Write faces grouped by material
        for texture_path, triangle_indices_set in texture_to_triangles.items():
            # Generate unique material name
            material_name = self._get_or_create_material(
                element_type, texture_path
            )
            
            # Write material directive
            obj_file.write(f"usemtl {material_name}\n")
            
            # Write triangles (sort for deterministic output)
            for tri_idx in sorted(triangle_indices_set):
                v1, v2, v3 = indices[tri_idx]
                
                # OBJ uses 1-based indexing
                # Format: f v1/vt1/vn1 v2/vt2/vn2 v3/vt3/vn3
                # Note: Vertex order is reversed (v1, v3, v2) to flip face winding
                # This ensures normals point outward instead of inward
                v1_idx = vertex_offset + v1 + 1
                v2_idx = vertex_offset + v2 + 1
                v3_idx = vertex_offset + v3 + 1
                
                # Map vertices to texture coordinates using per-face UV mapping
                # Get UV indices from the mapping (triangle_idx, position_in_triangle)
                uv1 = vertex_to_uv_map.get((tri_idx, 0), v1)
                uv2 = vertex_to_uv_map.get((tri_idx, 1), v2)
                uv3 = vertex_to_uv_map.get((tri_idx, 2), v3)
                vt1_idx = texcoord_offset + uv1 + 1
                vt2_idx = texcoord_offset + uv2 + 1
                vt3_idx = texcoord_offset + uv3 + 1
                
                # Use per-face normal (same for all vertices in triangle)
                vn_idx = normal_offset + tri_idx + 1
                
                # Reversed winding: v1, v3, v2 instead of v1, v2, v3
                obj_file.write(f"f {v1_idx}/{vt1_idx}/{vn_idx} "
                             f"{v3_idx}/{vt3_idx}/{vn_idx} "
                             f"{v2_idx}/{vt2_idx}/{vn_idx}\n")
            
            obj_file.write("\n")
    
    def _get_or_create_material(self, element_type: str, texture_path: Path) -> str:
        """
        Get or create material name for element type and texture.
        
        Args:
            element_type: Type of element
            texture_path: Path to texture file
            
        Returns:
            Unique material name
        """
        # Generate material name from element type and texture filename
        texture_name = texture_path.stem  # filename without extension
        material_name = f"{element_type}_{texture_name}_material"
        
        # If material already exists, return it
        if material_name in self.materials:
            return material_name
        
        # Get material properties from MaterialManager
        properties = self.material_manager.get_material_for_texture(texture_path, element_type)
        
        # Create new material entry
        self.materials[material_name] = {
            'element_type': element_type,
            'texture_path': texture_path,
            'properties': properties,
        }
        
        # Copy texture to output directory
        # Use just the filename (textures will be in output/textures/ directory)
        relative_path = texture_path.name
        self.texture_manager.copy_texture_to_output(texture_path, relative_path)
        
        return material_name
    
    def _write_mtl_file(self, mtl_file):
        """Write MTL file content."""
        
        mtl_file.write("# Material Library\n")
        mtl_file.write(f"# Floor Plan: {self.floor_plan.title}\n")
        mtl_file.write("# Generated by floor_planner\n")
        mtl_file.write("\n")
        
        for material_name, material_data in self.materials.items():
            props = material_data['properties']
            texture_path = material_data['texture_path']
            
            mtl_file.write(f"newmtl {material_name}\n")
            mtl_file.write(f"Ka {self.material_manager.format_mtl_color(props['Ka'])}\n")
            mtl_file.write(f"Kd {self.material_manager.format_mtl_color(props['Kd'])}\n")
            mtl_file.write(f"Ks {self.material_manager.format_mtl_color(props['Ks'])}\n")
            mtl_file.write(f"Ns {props['Ns']:.1f}\n")
            
            # Check if texture is PNG (supports alpha channel)
            is_png = texture_path.suffix.lower() == '.png'
            
            # Add transparency support for PNG files
            if is_png:
                mtl_file.write(f"d 1.0\n")  # Dissolve (opacity): 1.0 = fully opaque
                mtl_file.write(f"Tr 0.0\n")  # Transparency: 0.0 = fully opaque (alternative format)
            
            # Texture reference (relative to MTL file location)
            texture_rel_path = self.texture_manager.get_relative_texture_path(texture_path)
            mtl_file.write(f"map_Kd {texture_rel_path}\n")
            
            # Add alpha map for PNG files (uses same texture's alpha channel)
            if is_png:
                mtl_file.write(f"map_d {texture_rel_path}\n")
            
            mtl_file.write("\n")
    
    def _generate_box_texcoords(self, element, vertices: list[tuple[float, float, float]]) -> tuple[list[tuple[float, float]], dict]:
        """
        Generate proper box-mapped texture coordinates with per-face UV mapping.
        
        Generates 24 texture coordinates (4 per face × 6 faces) so each face can have
        proper UV mapping based on its dimensions. Also returns a mapping from vertex
        indices to texture coordinate indices for each face.
        
        Args:
            element: The floor plan element (to access dimensions and texture_scale)
            vertices: List of vertex coordinates (to calculate actual dimensions)
            
        Returns:
            Tuple of:
            - List of (u, v) texture coordinates (24 coords for box)
            - Dict mapping face triangle indices to texcoord indices
        """
        vertex_count = len(vertices)
        
        if vertex_count != 8:
            # Fallback for non-box geometries
            base_coords = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)]
            coords = [base_coords[i % 4] for i in range(vertex_count)]
            return coords, {}
        
        # Calculate physical dimensions from vertices
        # Box layout: vertices 0-3 are bottom corners, 4-7 are top corners
        # 0: front-left-bottom, 1: front-right-bottom, 2: back-right-bottom, 3: back-left-bottom
        # 4: front-left-top, 5: front-right-top, 6: back-right-top, 7: back-left-top
        length = ((vertices[1][0] - vertices[0][0])**2 + 
                 (vertices[1][2] - vertices[0][2])**2)**0.5
        thickness = ((vertices[3][0] - vertices[0][0])**2 + 
                    (vertices[3][2] - vertices[0][2])**2)**0.5
        height = abs(vertices[4][1] - vertices[0][1])
        
        # Get texture scale parameter for tiling
        texture_scale = getattr(element, 'texture_scale', None)
        
        # Calculate UV repeats based on physical size (or default to 1.0 for stretch-to-fit)
        if texture_scale and texture_scale > 0:
            u_length = length / texture_scale
            u_thickness = thickness / texture_scale
            v_height = height / texture_scale
        else:
            u_length = 1.0
            u_thickness = 1.0
            v_height = 1.0
        
        # Generate 24 UVs: 4 corners per face × 6 faces
        # Each face gets its own set of 4 UVs based on its dimensions
        coords = []
        
        # Bottom face (indices 0-3 in geometry): length × thickness
        # Triangles: (0,2,1) and (0,3,2)
        coords.extend([
            (0.0, 0.0),           # UV 0: for vertex 0
            (u_length, 0.0),      # UV 1: for vertex 1
            (u_length, u_thickness),  # UV 2: for vertex 2
            (0.0, u_thickness),   # UV 3: for vertex 3
        ])
        
        # Top face (indices 4-7): length × thickness
        # Triangles: (4,5,6) and (4,6,7)
        coords.extend([
            (0.0, 0.0),           # UV 4: for vertex 4
            (u_length, 0.0),      # UV 5: for vertex 5
            (u_length, u_thickness),  # UV 6: for vertex 6
            (0.0, u_thickness),   # UV 7: for vertex 7
        ])
        
        # Front face (vertices 0,1,5,4): length × height
        # Triangles: (0,1,5) and (0,5,4)
        coords.extend([
            (0.0, 0.0),           # UV 8: for vertex 0
            (u_length, 0.0),      # UV 9: for vertex 1
            (u_length, v_height), # UV 10: for vertex 5
            (0.0, v_height),      # UV 11: for vertex 4
        ])
        
        # Back face (vertices 2,3,7,6): length × height
        # Triangles: (2,3,7) and (2,7,6)
        coords.extend([
            (u_length, 0.0),      # UV 12: for vertex 2
            (0.0, 0.0),           # UV 13: for vertex 3
            (0.0, v_height),      # UV 14: for vertex 7
            (u_length, v_height), # UV 15: for vertex 6
        ])
        
        # Right face (vertices 1,2,6,5): thickness × height
        # Triangles: (1,2,6) and (1,6,5)
        coords.extend([
            (0.0, 0.0),           # UV 16: for vertex 1
            (u_thickness, 0.0),   # UV 17: for vertex 2
            (u_thickness, v_height), # UV 18: for vertex 6
            (0.0, v_height),      # UV 19: for vertex 5
        ])
        
        # Left face (vertices 3,0,4,7): thickness × height
        # Triangles: (3,0,4) and (3,4,7)
        coords.extend([
            (u_thickness, 0.0),   # UV 20: for vertex 3
            (0.0, 0.0),           # UV 21: for vertex 0
            (0.0, v_height),      # UV 22: for vertex 4
            (u_thickness, v_height), # UV 23: for vertex 7
        ])
        
        # Create mapping from (triangle_index, vertex_in_triangle) to UV index
        # This maps which UV to use for each vertex in each triangle
        vertex_to_uv_map = {
            # Bottom face triangles (0-1): triangle indices [0, 1]
            (0, 0): 0, (0, 1): 2, (0, 2): 1,  # Triangle (0,2,1)
            (1, 0): 0, (1, 1): 3, (1, 2): 2,  # Triangle (0,3,2)
            
            # Top face triangles (2-3): triangle indices [2, 3]
            (2, 0): 4, (2, 1): 5, (2, 2): 6,  # Triangle (4,5,6)
            (3, 0): 4, (3, 1): 6, (3, 2): 7,  # Triangle (4,6,7)
            
            # Front face triangles (4-5): triangle indices [4, 5]
            (4, 0): 8, (4, 1): 9, (4, 2): 10,  # Triangle (0,1,5)
            (5, 0): 8, (5, 1): 10, (5, 2): 11, # Triangle (0,5,4)
            
            # Back face triangles (6-7): triangle indices [6, 7]
            (6, 0): 12, (6, 1): 13, (6, 2): 14, # Triangle (2,3,7)
            (7, 0): 12, (7, 1): 14, (7, 2): 15, # Triangle (2,7,6)
            
            # Right face triangles (8-9): triangle indices [8, 9]
            (8, 0): 16, (8, 1): 17, (8, 2): 18, # Triangle (1,2,6)
            (9, 0): 16, (9, 1): 18, (9, 2): 19, # Triangle (1,6,5)
            
            # Left face triangles (10-11): triangle indices [10, 11]
            (10, 0): 20, (10, 1): 21, (10, 2): 22, # Triangle (3,0,4)
            (11, 0): 20, (11, 1): 22, (11, 2): 23, # Triangle (3,4,7)
        }
        
        return coords, vertex_to_uv_map
    
    def _generate_element_texcoords(self, element, vertices: list[tuple[float, float, float]], 
                                    indices: list[tuple[int, int, int]],
                                    face_groups: dict[str, list[int]]) -> tuple[list[tuple[float, float]], dict]:
        """
        Generate texture coordinates for element based on its geometry type.
        
        Routes to appropriate UV generation:
        - 8-vertex box: Use standard box mapping
        - Complex geometry (walls with openings): Use per-face planar mapping
        
        Args:
            element: The floor plan element
            vertices: List of vertex coordinates
            indices: List of triangle indices
            face_groups: Dict mapping face names to triangle indices
            
        Returns:
            Tuple of (texcoords, vertex_to_uv_map)
        """
        vertex_count = len(vertices)
        
        # For simple 8-vertex boxes (furniture, doors, windows, simple walls)
        if vertex_count == 8:
            return self._generate_box_texcoords(element, vertices)
        
        # For complex geometry (walls with openings), use per-face planar mapping
        return self._generate_planar_texcoords(element, vertices, indices, face_groups)
    
    def _generate_planar_texcoords(self, element, vertices: list[tuple[float, float, float]],
                                   indices: list[tuple[int, int, int]],
                                   face_groups: dict[str, list[int]]) -> tuple[list[tuple[float, float]], dict]:
        """
        Generate planar UV mapping for complex geometry (walls with openings).
        
        Each face gets UVs projected onto its plane based on the face's world-space
        position and dimensions. Supports texture tiling via texture_scale parameter.
        
        Args:
            element: The floor plan element (for texture_scale)
            vertices: List of vertex coordinates
            indices: List of triangle indices
            face_groups: Dict mapping face names to triangle indices
            
        Returns:
            Tuple of (texcoords, vertex_to_uv_map)
        """
        # Get texture scale for tiling
        texture_scale = getattr(element, 'texture_scale', None)
        if not texture_scale or texture_scale <= 0:
            texture_scale = 1.0
        
        # Create UV coordinate for each vertex (one UV per vertex)
        # We'll generate UVs by projecting each face onto its plane
        texcoords = []
        vertex_to_uv_map = {}
        
        # Track which vertices have been assigned UVs
        vertex_to_uv_idx = {}
        
        # Process each face group
        for face_name, triangle_indices in face_groups.items():
            # Skip aggregate groups
            if face_name in ('all', 'sides'):
                continue
            
            if not triangle_indices:
                continue
            
            # Determine projection plane for this face
            # Get first triangle to determine face orientation
            tri_idx = triangle_indices[0]
            v1_idx, v2_idx, v3_idx = indices[tri_idx]
            v1, v2, v3 = vertices[v1_idx], vertices[v2_idx], vertices[v3_idx]
            
            # Calculate face normal
            edge1 = (v2[0] - v1[0], v2[1] - v1[1], v2[2] - v1[2])
            edge2 = (v3[0] - v1[0], v3[1] - v1[1], v3[2] - v1[2])
            nx = edge1[1] * edge2[2] - edge1[2] * edge2[1]
            ny = edge1[2] * edge2[0] - edge1[0] * edge2[2]
            nz = edge1[0] * edge2[1] - edge1[1] * edge2[0]
            
            # Normalize
            length = math.sqrt(nx*nx + ny*ny + nz*nz)
            if length > 0.0001:
                nx /= length
                ny /= length
                nz /= length
            
            # Determine which plane to project onto based on dominant normal direction
            # Choose the two axes perpendicular to the normal
            abs_nx, abs_ny, abs_nz = abs(nx), abs(ny), abs(nz)
            
            if abs_ny > abs_nx and abs_ny > abs_nz:
                # Horizontal face (floor/ceiling) - use XZ plane
                u_axis, v_axis = 0, 2  # X and Z
            elif abs_nx > abs_nz:
                # Face parallel to YZ plane - use ZY plane
                u_axis, v_axis = 2, 1  # Z and Y
            else:
                # Face parallel to XY plane - use XY plane
                u_axis, v_axis = 0, 1  # X and Y
            
            # Collect all vertices used in this face
            face_vertices_indices = set()
            for tri_idx in triangle_indices:
                v1, v2, v3 = indices[tri_idx]
                face_vertices_indices.update([v1, v2, v3])
            
            # Find bounding box of face in projection plane
            min_u = min_v = float('inf')
            max_u = max_v = float('-inf')
            for v_idx in face_vertices_indices:
                u_coord = vertices[v_idx][u_axis]
                v_coord = vertices[v_idx][v_axis]
                min_u = min(min_u, u_coord)
                max_u = max(max_u, u_coord)
                min_v = min(min_v, v_coord)
                max_v = max(max_v, v_coord)
            
            face_width = max_u - min_u
            face_height = max_v - min_v
            
            # Generate UV for each vertex in this face
            for v_idx in face_vertices_indices:
                # Skip if already assigned
                if v_idx in vertex_to_uv_idx:
                    continue
                
                # Project vertex onto face plane
                u_coord = vertices[v_idx][u_axis]
                v_coord = vertices[v_idx][v_axis]
                
                # Normalize to [0, 1] range and apply texture scale
                if face_width > 0.0001:
                    u = (u_coord - min_u) / texture_scale
                else:
                    u = 0.0
                
                if face_height > 0.0001:
                    v = (v_coord - min_v) / texture_scale
                else:
                    v = 0.0
                
                # Add UV coordinate
                uv_idx = len(texcoords)
                texcoords.append((u, v))
                vertex_to_uv_idx[v_idx] = uv_idx
            
            # Map triangles to UV indices
            for tri_idx in triangle_indices:
                v1, v2, v3 = indices[tri_idx]
                vertex_to_uv_map[(tri_idx, 0)] = vertex_to_uv_idx[v1]
                vertex_to_uv_map[(tri_idx, 1)] = vertex_to_uv_idx[v2]
                vertex_to_uv_map[(tri_idx, 2)] = vertex_to_uv_idx[v3]
        
        # Handle any vertices not in face groups (shouldn't happen but be safe)
        for v_idx in range(len(vertices)):
            if v_idx not in vertex_to_uv_idx:
                texcoords.append((0.0, 0.0))
                vertex_to_uv_idx[v_idx] = len(texcoords) - 1
        
        return texcoords, vertex_to_uv_map
    
    def _calculate_normals(self, vertices: list[tuple[float, float, float]], 
                          indices: list[tuple[int, int, int]]) -> list[tuple[float, float, float]]:
        """
        Calculate face normals for triangles.
        
        Args:
            vertices: List of vertex coordinates
            indices: List of triangle vertex indices
            
        Returns:
            List of normal vectors (one per triangle, not per vertex)
        """
        normals = []
        
        for v1_idx, v2_idx, v3_idx in indices:
            v1 = vertices[v1_idx]
            v2 = vertices[v2_idx]
            v3 = vertices[v3_idx]
            
            # Calculate edge vectors
            edge1 = (v2[0] - v1[0], v2[1] - v1[1], v2[2] - v1[2])
            edge2 = (v3[0] - v1[0], v3[1] - v1[1], v3[2] - v1[2])
            
            # Cross product for normal
            # Note: Negated to match reversed face winding (outward-facing normals)
            nx = -(edge1[1] * edge2[2] - edge1[2] * edge2[1])
            ny = -(edge1[2] * edge2[0] - edge1[0] * edge2[2])
            nz = -(edge1[0] * edge2[1] - edge1[1] * edge2[0])
            
            # Normalize
            length = math.sqrt(nx*nx + ny*ny + nz*nz)
            if length > 0.0001:
                nx /= length
                ny /= length
                nz /= length
            
            normals.append((nx, ny, nz))
        
        return normals
    
    def _sanitize_filename(self, filename: str) -> str:
        """
        Sanitize filename for filesystem compatibility.
        
        Args:
            filename: Original filename
            
        Returns:
            Sanitized filename
        """
        # Replace spaces and special chars with underscores
        safe = filename.replace(' ', '_')
        safe = ''.join(c for c in safe if c.isalnum() or c in ('_', '-'))
        return safe.lower()


